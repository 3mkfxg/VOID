let currentLang = "en";

document.addEventListener("DOMContentLoaded", () => {
  const langToggleBtn = document.getElementById("langToggle");
  const langToggleText = document.getElementById("langToggleText");
  const mobileMenuBtn = document.getElementById("mobileMenuBtn");
  const navLinks = document.getElementById("navLinks");
  const selectedPackageSelect = document.getElementById("selectedPackage");
  const projectForm = document.getElementById("projectForm");
  const formSuccess = document.getElementById("formSuccess");
  const formSuccessDetails = document.getElementById("formSuccessDetails");

  // Interactive Calculator Elements
  const calcAdminToggle = document.getElementById("calcAdminToggle");
  const calcMainToggle = document.getElementById("calcMainToggle");
  const calcResultCode = document.getElementById("calcResultCode");
  const calcResultPrice = document.getElementById("calcResultPrice");
  const calcResultDesc = document.getElementById("calcResultDesc");
  const calcSelectBtn = document.getElementById("calcSelectBtn");

  // Update Footer Year
  const yearEl = document.getElementById("currentYear");
  if (yearEl) {
    yearEl.textContent = new Date().getFullYear();
  }

  // Mobile Menu Toggle
  if (mobileMenuBtn && navLinks) {
    mobileMenuBtn.addEventListener("click", () => {
      navLinks.classList.toggle("active");
    });

    navLinks.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => {
        navLinks.classList.remove("active");
      });
    });
  }

  // Language Switcher
  function setLanguage(lang) {
    currentLang = lang;
    const dict = translations[lang];
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    langToggleText.textContent = lang === "ar" ? "English" : "العربية";

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (dict[key]) {
        el.setAttribute("placeholder", dict[key]);
      }
    });

    updateCalculator();
  }

  if (langToggleBtn) {
    langToggleBtn.addEventListener("click", () => {
      const nextLang = currentLang === "en" ? "ar" : "en";
      setLanguage(nextLang);
    });
  }

  // Select Plan Buttons -> Scroll to Contact Form & Pre-select Package
  document.querySelectorAll(".select-plan-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const planValue = btn.getAttribute("data-plan");
      if (selectedPackageSelect && planValue) {
        selectedPackageSelect.value = planValue;
      }
      const contactSection = document.getElementById("contact");
      if (contactSection) {
        contactSection.scrollIntoView({ behavior: "smooth" });
      }
    });
  });

  // Interactive Calculator Logic
  let currentCalcPlanValue = "WEB - 150 JOD";

  function updateCalculator() {
    if (!calcAdminToggle || !calcMainToggle) return;
    const dict = translations[currentLang];
    const wantsAdmin = calcAdminToggle.checked;
    const wantsMain = calcMainToggle.checked;

    if (!wantsAdmin && !wantsMain) {
      calcResultCode.textContent = "WEB";
      calcResultPrice.textContent = "150";
      calcResultDesc.textContent = dict.calc_desc_web;
      currentCalcPlanValue = "WEB - 150 JOD";
    } else if (wantsAdmin && !wantsMain) {
      calcResultCode.textContent = "FULL STACK";
      calcResultPrice.textContent = "225";
      calcResultDesc.textContent = dict.calc_desc_fs;
      currentCalcPlanValue = "FULL STACK (With Admin Page) - 225 JOD";
    } else if (!wantsAdmin && wantsMain) {
      calcResultCode.textContent = "MAIN";
      calcResultPrice.textContent = "300";
      calcResultDesc.textContent = dict.calc_desc_main;
      currentCalcPlanValue = "MAIN (Web + Maintenance) - 300 JOD";
    } else {
      calcResultCode.textContent = "MAIN + FULL STACK";
      calcResultPrice.textContent = "450";
      calcResultDesc.textContent = dict.calc_desc_main_fs;
      currentCalcPlanValue = "MAIN + FULL STACK - 450 JOD";
    }
  }

  if (calcAdminToggle && calcMainToggle) {
    calcAdminToggle.addEventListener("change", updateCalculator);
    calcMainToggle.addEventListener("change", updateCalculator);
  }

  if (calcSelectBtn) {
    calcSelectBtn.addEventListener("click", () => {
      if (selectedPackageSelect) {
        selectedPackageSelect.value = currentCalcPlanValue;
      }
      const contactSection = document.getElementById("contact");
      if (contactSection) {
        contactSection.scrollIntoView({ behavior: "smooth" });
      }
    });
  }

  // Contact Form Submission Handling
  if (projectForm) {
    projectForm.addEventListener("submit", (e) => {
      e.preventDefault();
      const name = document.getElementById("clientName").value.trim();
      const store = document.getElementById("storeName").value.trim();
      const phone = document.getElementById("clientPhone").value.trim();
      const pkg = selectedPackageSelect.value;

      if (formSuccess && formSuccessDetails) {
        if (currentLang === "ar") {
          formSuccessDetails.textContent = `تم تسجيل طلب متجر "${store}" (${name}) للباقة: ${pkg}. سنتواصل معك قريباً على الرقم ${phone}.`;
        } else {
          formSuccessDetails.textContent = `We logged ${name}'s request for "${store}" — Package: ${pkg}. Our team will contact you shortly at ${phone}.`;
        }
        formSuccess.hidden = false;
      }

      projectForm.reset();
      selectedPackageSelect.value = pkg;
    });
  }
});
